# Khung ngày chuẩn để đảm bảo không lệch dòng khi pivot
df_dates_spine = pl.DataFrame({"trade_date": sim_dates})

def pivot_matrix(df: pl.DataFrame, val_col: str, fill_val=0.0, ffill: bool = False) -> np.ndarray:
    piv = (
        df.pivot(index="trade_date", on="ticker", values=val_col)
        .sort("trade_date")
    )
    piv = df_dates_spine.join(piv, on="trade_date", how="left").sort("trade_date")
    for tk in tickers:
        if tk not in piv.columns:
            piv = piv.with_columns(pl.lit(None).alias(tk))
    piv = piv.select(tickers)
    if ffill:
        # Bắt buộc forward_fill cho giá để không bao giờ định giá cổ phiếu bằng 0 đồng
        piv = piv.with_columns([pl.col(tk).forward_fill().backward_fill() for tk in tickers])
    return piv.fill_null(fill_val).to_numpy()

close_mat = pivot_matrix(df_market_aligned, "close", fill_val=0.0, ffill=True)
open_mat = pivot_matrix(df_market_aligned, "open", fill_val=0.0, ffill=True)
mult_mat = pivot_matrix(df_market_aligned, "shares_multiplier", fill_val=1.0, ffill=False)
ceil_mat = pivot_matrix(df_market_aligned, "is_ceiling", fill_val=False, ffill=False).astype(bool)
floor_mat = pivot_matrix(df_market_aligned, "is_floor", fill_val=False, ffill=False).astype(bool)
target_w_mat = df_weights_sorted.select(tickers).to_numpy()

