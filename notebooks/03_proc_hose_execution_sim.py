"""# Hàm Tính Hệ Số Co Giãn Rolling High-Water Mark (HWM Soft-Landing)"""

def compute_hwm_scalar(nav_history: list[float], cfg: dict) -> tuple[float, float]:
    """
    Tính toán hệ số co giãn tỷ trọng danh mục dựa trên Rolling High-Water Mark.
    Trả về: (alpha_exposure, current_drawdown)
    """
    if len(nav_history) == 0:
        return 1.0, 0.0

    window = nav_history[-cfg["hwm_window"]:]
    hwm = max(window)
    curr_nav = nav_history[-1]
    dd = max(0.0, 1.0 - (curr_nav / hwm))

    dd_start = cfg["dd_soft_start"]
    dd_stop = cfg["dd_hard_stop"]
    floor_exp = cfg["min_exposure_floor"]

    if dd <= dd_start:
        return 1.0, dd
    elif dd >= dd_stop:
        return floor_exp, dd
    else:
        # Giảm tuyến tính từ 1.0 xuống floor_exp khi Drawdown trượt từ dd_start -> dd_stop
        slope = (1.0 - floor_exp) / (dd_stop - dd_start)
        alpha = 1.0 - slope * (dd - dd_start)
        return float(alpha), dd

"""# Vòng Lặp Mô Phỏng Khớp Lệnh Thực Tế Sàn HOSE (Event-Driven Loop)"""

n_days, n_assets = close_mat.shape
cash = float(EXEC_CONFIG["initial_capital_vnd"])

# Số lượng cổ phiếu khả dụng (đã về tài khoản, có thể bán ngay)
avail_shares = np.zeros(n_assets, dtype=np.int64)
# Hàng đợi cổ phiếu mới mua chưa về tài khoản: list các tuple (unlock_day_idx, ticker_idx, qty)
pending_settlement = []

nav_history = []
ledger_records = []
trade_records = []

lot = EXEC_CONFIG["lot_size"]
buf = EXEC_CONFIG["no_trade_buffer"]
buy_fee = EXEC_CONFIG["buy_fee_rate"]
sell_cost = EXEC_CONFIG["sell_fee_rate"] + EXEC_CONFIG["sell_tax_rate"]

for t in range(n_days):
    d = sim_dates[t]
    prices = close_mat[t]

    # 1. Giải phóng các lô cổ phiếu đã hoàn tất chu kỳ thanh toán T+2.5 vào đầu phiên t
    still_pending = []
    for unlock_t, tk_idx, qty in pending_settlement:
        if t >= unlock_t:
            avail_shares[tk_idx] += qty
        else:
            still_pending.append((unlock_t, tk_idx, qty))
    pending_settlement = still_pending

    # 2. Cập nhật sự kiện quyền (cổ tức / chia tách) thông qua shares_multiplier từ Phần 1
    # Phần cổ phiếu lẻ phát sinh (nếu có) được quy đổi thành tiền mặt cổ tức
    if t > 0:
        for i in range(n_assets):
            m = mult_mat[t, i]
            if abs(m - 1.0) > 1e-6 and prices[i] > 0:
                old_avail = avail_shares[i]
                new_avail_exact = old_avail * m
                new_avail_int = int(np.floor(new_avail_exact))
                cash += (new_avail_exact - new_avail_int) * prices[i]
                avail_shares[i] = new_avail_int

        # Cập nhật tương tự cho các lô đang chờ về
        updated_pending = []
        for unlock_t, tk_idx, qty in pending_settlement:
            m = mult_mat[t, tk_idx]
            if abs(m - 1.0) > 1e-6 and prices[tk_idx] > 0:
                new_q_exact = qty * m
                new_q_int = int(np.floor(new_q_exact))
                cash += (new_q_exact - new_q_int) * prices[tk_idx]
                updated_pending.append((unlock_t, tk_idx, new_q_int))
            else:
                updated_pending.append((unlock_t, tk_idx, qty))
        pending_settlement = updated_pending

    # Tính tổng số cổ phiếu sở hữu (khả dụng + đang chờ về)
    locked_shares = np.zeros(n_assets, dtype=np.int64)
    for _, tk_idx, qty in pending_settlement:
        locked_shares[tk_idx] += qty
    total_shares = avail_shares + locked_shares

    # 3. Định giá NAV trước giao dịch & Tính hệ số bảo vệ Rolling HWM
    stock_value = np.sum(total_shares * prices)
    pre_trade_nav = cash + stock_value

    hwm_alpha, curr_dd = compute_hwm_scalar(nav_history, EXEC_CONFIG)
    # Tỷ trọng mục tiêu thực tế sau khi nhân lớp phủ phòng thủ HWM
    adj_target_weights = target_w_mat[t] * hwm_alpha

    current_weights = np.where(pre_trade_nav > 0, (total_shares * prices) / pre_trade_nav, 0.0)
    daily_turnover_vnd = 0.0
    daily_fees_vnd = 0.0

    # Chỉ tái cân bằng danh mục vào đúng ngày định kỳ (is_rebalance_day)
    # HOẶC khi hệ thống bảo vệ HWM kích hoạt hạ tỷ trọng phòng thủ (hwm_alpha giảm)
    prev_alpha = ledger_records[-1]["hwm_alpha"] if len(ledger_records) > 0 else 1.0
    should_trade = rebal_flags[t] or (hwm_alpha < prev_alpha - 1e-4)

    if should_trade:
        # 4. THỰC THI LỆNH BÁN TRƯỚC (Tái cân bằng giảm tỷ trọng & thu hồi tiền mặt)
        for i in range(n_assets):
            if prices[i] <= 0 or floor_mat[t, i]:
                continue  # Bỏ qua nếu giá lỗi hoặc cổ phiếu đang dư bán sàn

            w_diff = adj_target_weights[i] - current_weights[i]
            # Chỉ bán khi tỷ trọng hiện tại vượt mục tiêu lớn hơn vùng đệm (hoặc mục tiêu = 0)
            if w_diff < -buf or (adj_target_weights[i] == 0.0 and avail_shares[i] > 0):
                target_val = adj_target_weights[i] * pre_trade_nav
                curr_val = total_shares[i] * prices[i]
                sell_val_needed = curr_val - target_val

                # Quy đổi ra số lô chẵn 100 cổ phiếu và bị giới hạn bởi số cổ phiếu KHẢ DỤNG (T+2.5)
                raw_sell_qty = int(np.floor(sell_val_needed / prices[i] / lot)) * lot
                sell_qty = min(raw_sell_qty, int(avail_shares[i]))

                if sell_qty >= lot:
                    gross_proceeds = sell_qty * prices[i]
                    fee_and_tax = gross_proceeds * sell_cost
                    net_proceeds = gross_proceeds - fee_and_tax

                    avail_shares[i] -= sell_qty
                    cash += net_proceeds
                    daily_turnover_vnd += gross_proceeds
                    daily_fees_vnd += fee_and_tax

                    trade_records.append({
                        "trade_date": d, "ticker": tickers[i], "side": "SELL",
                        "qty": sell_qty, "price": prices[i], "gross_vnd": gross_proceeds, "fee_tax_vnd": fee_and_tax
                    })

        # 5. THỰC THI LỆNH MUA SAU (Sử dụng tiền mặt hiện có, làm tròn lô 100 cp, chặn giá trần)
        # Ưu tiên mua các mã thiếu hụt tỷ trọng nhiều nhất trước
        buy_candidates = []
        for i in range(n_assets):
            if prices[i] <= 0 or ceil_mat[t, i]:
                continue  # Chặn mua đuổi khi cổ phiếu dư mua trần
            w_diff = adj_target_weights[i] - current_weights[i]
            if w_diff > buf:
                buy_candidates.append((w_diff, i))

        buy_candidates.sort(reverse=True)  # Ưu tiên mã lệch mục tiêu lớn nhất

        for w_diff, i in buy_candidates:
            target_val = adj_target_weights[i] * pre_trade_nav
            # Tính lại giá trị đang nắm giữ hiện tại của mã i
            curr_locked = sum(q for _, idx, q in pending_settlement if idx == i)
            curr_val = (avail_shares[i] + curr_locked) * prices[i]
            buy_val_needed = target_val - curr_val

            if buy_val_needed <= 0:
                continue

            # Giới hạn bởi sức mua tiền mặt thực tế (đã trừ phí mua)
            max_affordable_val = cash / (1.0 + buy_fee)
            actual_buy_val = min(buy_val_needed, max_affordable_val)
            buy_qty = int(np.floor(actual_buy_val / prices[i] / lot)) * lot

            if buy_qty >= lot:
                gross_cost = buy_qty * prices[i]
                fee = gross_cost * buy_fee
                total_outflow = gross_cost + fee

                if total_outflow <= cash:
                    cash -= total_outflow
                    # Đưa vào hàng đợi thanh toán T+2.5
                    pending_settlement.append((t + EXEC_CONFIG["settlement_days"], i, buy_qty))
                    daily_turnover_vnd += gross_cost
                    daily_fees_vnd += fee

                    trade_records.append({
                        "trade_date": d, "ticker": tickers[i], "side": "BUY",
                        "qty": buy_qty, "price": prices[i], "gross_vnd": gross_cost, "fee_tax_vnd": fee
                    })

    # 6. Chốt sổ NAV cuối phiên t
    locked_after = np.zeros(n_assets, dtype=np.int64)
    for _, tk_idx, qty in pending_settlement:
        locked_after[tk_idx] += qty
    end_stock_val = np.sum((avail_shares + locked_after) * prices)
    end_nav = cash + end_stock_val

    nav_history.append(end_nav)
    prev_eod_nav = nav_history[-2] if len(nav_history) >= 2 else float(EXEC_CONFIG["initial_capital_vnd"])
    net_daily_ret = (end_nav / prev_eod_nav) - 1.0

    ledger_records.append({
        "trade_date": d,
        "nav_vnd": end_nav,
        "cash_vnd": cash,
        "stock_value_vnd": end_stock_val,
        "actual_stock_weight": end_stock_val / end_nav if end_nav > 0 else 0.0,
        "target_stock_weight": float(np.sum(adj_target_weights)),
        "hwm_alpha": hwm_alpha,
        "drawdown": curr_dd,
        "net_daily_return": net_daily_ret,
        "turnover_vnd": daily_turnover_vnd,
        "fees_tax_vnd": daily_fees_vnd
    })

df_ledger = pl.DataFrame(ledger_records)
df_trades = pl.DataFrame(trade_records) if len(trade_records) > 0 else pl.DataFrame()

print(f"Hoàn tất mô phỏng thực tế {len(df_ledger)} phiên | Tổng số lệnh khớp: {len(df_trades):,}")
display(df_ledger.tail(10))

