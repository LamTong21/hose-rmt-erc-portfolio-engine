ACTIONS_SCHEMA = {
    "ticker": pl.String,
    "ex_date": pl.Date,
    "payment_date": pl.Date,
    "action_type": pl.String,
    "cash_per_share": pl.Float64,
    "share_ratio": pl.Float64,
    "issue_price": pl.Float64,
}


def fetch_vn100_yfinance(
    start_date: str,
    end_date: str,
    cache_dir: Path,
) -> tuple[pl.DataFrame, pl.DataFrame]:
    """Kéo dữ liệu lịch sử OHLCV và Sự kiện quyền (Cổ tức/Chia tách) cho rổ VN100 qua yfinance."""
    cache_dir.mkdir(parents=True, exist_ok=True)
    symbols = sorted(set(FALLBACK_VN100))
    vn_tickers = [f"{s}.VN" for s in symbols]

    print(f"Bắt đầu tải hàng loạt {len(symbols)} mã VN100 từ Yahoo Finance ({start_date} -> {end_date})...")

    # 1. Tải song song toàn bộ OHLCV + Dividends + Stock Splits trong 1 lần gọi
    raw_pd = yf.download(
        tickers=vn_tickers,
        start=start_date,
        end=end_date,
        interval="1d",
        group_by="ticker",
        auto_adjust=False,  # Giữ giá gốc (Close) tách biệt với Adj Close
        actions=True,       # Kéo kèm Dividends và Stock Splits
        threads=True,
        progress=True,
    )

    market_dfs: list[pl.DataFrame] = []
    action_dfs: list[pl.DataFrame] = []
    failed_tickers: list[str] = []

    for sym, yf_sym in zip(symbols, vn_tickers):
        try:
            if isinstance(raw_pd.columns, pd.MultiIndex):
                if yf_sym not in raw_pd.columns.get_level_values(0):
                    failed_tickers.append(sym)
                    continue
                sub = raw_pd[yf_sym].copy()
            else:
                sub = raw_pd.copy()

            sub = sub.reset_index()
            date_col = "Date" if "Date" in sub.columns else sub.columns[0]
            sub["trade_date"] = pd.to_datetime(sub[date_col]).dt.date
            sub = sub.dropna(subset=["Close"])

            if sub.empty:
                failed_tickers.append(sym)
                continue

            # --- A. Chuẩn hóa OHLCV ---
            df_ohlc = (
                pl.DataFrame({
                    "ticker": [sym] * len(sub),
                    "trade_date": sub["trade_date"].tolist(),
                    "open": sub["Open"].astype(float).tolist(),
                    "high": sub["High"].astype(float).tolist(),
                    "low": sub["Low"].astype(float).tolist(),
                    "close": sub["Close"].astype(float).tolist(),
                    "volume_match": sub["Volume"].fillna(0).astype("int64").tolist(),
                })
                .with_columns(
                    (pl.col("close") * pl.col("volume_match")).alias("value_match")
                )
            )
            market_dfs.append(df_ohlc)

            # --- B. Bóc tách sự kiện cổ tức tiền mặt & chia tách cổ phiếu ---
            if "Dividends" in sub.columns:
                divs = sub[sub["Dividends"].fillna(0) > 0]
                if not divs.empty:
                    action_dfs.append(
                        pl.DataFrame({
                            "ticker": [sym] * len(divs),
                            "ex_date": divs["trade_date"].tolist(),
                            "payment_date": [None] * len(divs),
                            "action_type": ["CASH_DIVIDEND"] * len(divs),
                            "cash_per_share": divs["Dividends"].astype(float).tolist(),
                            "share_ratio": [0.0] * len(divs),
                            "issue_price": [0.0] * len(divs),
                        }, schema=ACTIONS_SCHEMA)
                    )

            if "Stock Splits" in sub.columns:
                splits = sub[sub["Stock Splits"].fillna(0) > 0]
                if not splits.empty:
                    action_dfs.append(
                        pl.DataFrame({
                            "ticker": [sym] * len(splits),
                            "ex_date": splits["trade_date"].tolist(),
                            "payment_date": [None] * len(splits),
                            "action_type": ["STOCK_DIVIDEND_OR_SPLIT"] * len(splits),
                            "cash_per_share": [0.0] * len(splits),
                            "share_ratio": (splits["Stock Splits"].astype(float) - 1.0).tolist(),
                            "issue_price": [0.0] * len(splits),
                        }, schema=ACTIONS_SCHEMA)
                    )

        except Exception:
            failed_tickers.append(sym)

    df_market_all = (
        pl.concat(market_dfs).unique(subset=["ticker", "trade_date"]).sort(["ticker", "trade_date"])
        if market_dfs else pl.DataFrame()
    )
    df_actions_all = (
        pl.concat(action_dfs).unique().sort(["ticker", "ex_date"])
        if action_dfs else pl.DataFrame(schema=ACTIONS_SCHEMA)
    )

    if not df_market_all.is_empty():
        df_market_all.write_parquet(cache_dir / "vn100_market_raw_cache.parquet", compression="zstd")
    if not df_actions_all.is_empty():
        df_actions_all.write_parquet(cache_dir / "vn100_actions_raw_cache.parquet", compression="zstd")

    success_count = df_market_all["ticker"].n_unique() if not df_market_all.is_empty() else 0
    print(f"\nHoàn tất! Thành công: {success_count}/{len(symbols)} mã | Thiếu dữ liệu: {len(failed_tickers)} mã.")
    if failed_tickers:
        print("Các mã không có trên Yahoo Finance:", failed_tickers)

    return df_market_all, df_actions_all


