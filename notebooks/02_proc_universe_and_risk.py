"""# Cell 3: Thuật Toán Khử Nhiễu RMT & Phân Cụm Phân Cấp Chọn Đại Diện (Correlation Clustering)"""

def denoise_correlation_rmt(returns_matrix: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """
    Trả về (corr_clean, stds) sau khi lọc nhiễu trị riêng Marchenko-Pastur.
    """
    T, N = returns_matrix.shape
    stds = np.std(returns_matrix, axis=0, ddof=1)
    stds = np.where(stds < 1e-8, 1e-8, stds)
    if N == 1:
        return np.ones((1, 1)), stds

    corr_matrix = np.corrcoef(returns_matrix, rowvar=False)
    corr_matrix = np.nan_to_num(corr_matrix, nan=0.0)
    np.fill_diagonal(corr_matrix, 1.0)

    eigenvalues, eigenvectors = np.linalg.eigh(corr_matrix)
    idx = eigenvalues.argsort()[::-1]
    eigenvalues, eigenvectors = eigenvalues[idx], eigenvectors[:, idx]

    q = N / float(T)
    lambda_plus = (1.0 + np.sqrt(q)) ** 2

    denoised_evals = eigenvalues.copy()
    noise_mask = denoised_evals <= lambda_plus
    if np.any(noise_mask) and not np.all(noise_mask):
        denoised_evals[noise_mask] = np.mean(denoised_evals[noise_mask])

    corr_clean = eigenvectors @ np.diag(denoised_evals) @ eigenvectors.T
    diag_sqrt = np.sqrt(np.diag(corr_clean))
    corr_clean = corr_clean / np.outer(diag_sqrt, diag_sqrt)
    corr_clean = np.clip(corr_clean, -1.0, 1.0)
    np.fill_diagonal(corr_clean, 1.0)
    return corr_clean, stds


def select_cluster_representatives(
    corr_clean: np.ndarray,
    stds: np.ndarray,
    adtvs: np.ndarray,
    n_clusters: int,
    valid_global_idx: np.ndarray,
    prev_selected_global: set[int],
    hysteresis_bonus: float = 1.25
) -> np.ndarray:
    """
    Phân cụm phân cấp Ward trên khoảng cách tương quan RMT.
    Tích hợp Hysteresis: ưu tiên giữ lại mã đang có trong danh mục nếu điểm chất lượng
    của nó không kém mã tốt nhất trong cụm quá (1 - 1/hysteresis_bonus).
    """
    N = corr_clean.shape[0]
    if N <= n_clusters:
        return np.arange(N)

    dist_mat = np.sqrt(np.maximum(0.0, 2.0 * (1.0 - corr_clean)))
    np.fill_diagonal(dist_mat, 0.0)
    condensed_dist = squareform(dist_mat, checks=False)

    Z = linkage(condensed_dist, method="ward")
    cluster_ids = fcluster(Z, t=n_clusters, criterion="maxclust")

    # Điểm chất lượng cơ sở
    base_metric = np.log1p(adtvs) / (stds ** 2 + 1e-8)

    # Cộng điểm thưởng giữ chỗ cho các mã đang nắm giữ
    adjusted_metric = base_metric.copy()
    for local_i, global_i in enumerate(valid_global_idx):
        if global_i in prev_selected_global:
            adjusted_metric[local_i] *= hysteresis_bonus

    selected_sub_idx = []
    for c_id in np.unique(cluster_ids):
        members = np.where(cluster_ids == c_id)[0]
        best_member = members[np.argmax(adjusted_metric[members])]
        selected_sub_idx.append(best_member)

    return np.sort(np.array(selected_sub_idx, dtype=int))

"""# Cell 4: Bộ Tối Ưu ERC & 2 Hàm Phân Bổ Đối Chứng (Inverse-Vol & Equal-Weight)"""

def optimize_erc_weights(cov_matrix: np.ndarray, max_weight: float = 0.15) -> np.ndarray:
    N = cov_matrix.shape[0]
    if N == 0:
        return np.array([])
    target_invested = min(1.0, N * max_weight)
    init_weights = np.repeat(target_invested / N, N)
    bounds = tuple((0.0, max_weight) for _ in range(N))

    def risk_budget_objective(w):
        port_var = w.T @ cov_matrix @ w
        if port_var <= 1e-12:
            return 0.0
        risk_contrib = w * (cov_matrix @ w)
        target_rc = port_var / N
        return np.sum((risk_contrib - target_rc) ** 2) * 1e6

    constraints = ({'type': 'eq', 'fun': lambda w: np.sum(w) - target_invested})
    res = minimize(
        risk_budget_objective, init_weights, method='SLSQP',
        bounds=bounds, constraints=constraints, options={'ftol': 1e-10, 'maxiter': 500}
    )
    weights = res.x if res.success else init_weights
    weights = np.where(weights < 0.001, 0.0, weights)
    if np.sum(weights) > 0:
        weights = weights * (target_invested / np.sum(weights))
    return weights


def cap_and_normalize_weights(raw_weights: np.ndarray, target_invested: float, max_weight: float) -> np.ndarray:
    """Phân bổ tỷ trọng có trần cứng (iterative capping) không bị vượt ngưỡng khi chuẩn hóa."""
    w = np.maximum(0.0, raw_weights.astype(float))
    if np.sum(w) <= 0:
        return np.zeros_like(w)

    w = w * (target_invested / np.sum(w))
    for _ in range(len(w)):
        over_mask = w > max_weight + 1e-12
        if not np.any(over_mask):
            break
        under_mask = w < max_weight - 1e-12
        if not np.any(under_mask):
            w = np.minimum(w, max_weight)
            break
        excess = np.sum(w[over_mask] - max_weight)
        w[over_mask] = max_weight
        w[under_mask] += excess * (w[under_mask] / np.sum(w[under_mask]))
    return w


def compute_benchmark_weights(stds: np.ndarray, max_weight: float = 0.15) -> tuple[np.ndarray, np.ndarray]:
    """
    Tính tỷ trọng đối chứng trên cùng rổ đại diện: (inv_vol_weights, equal_weights)
    """
    N = len(stds)
    target_invested = min(1.0, N * max_weight)

    # 1. Equal-Weight (1/N)
    w_eq = np.repeat(target_invested / N, N)

    # 2. Inverse-Volatility (1/sigma_i) với trần cứng chuẩn xác
    inv_v = 1.0 / np.maximum(stds, 1e-6)
    w_iv = cap_and_normalize_weights(inv_v, target_invested, max_weight)

    return w_iv, w_eq

"""# Cell 5: Chạy Mô Phỏng Walk-Forward & Xuất 3 Bảng Tỷ Trọng Đối Chứng"""

ret_mat = returns_wide.select(tickers_all).to_numpy()
elig_mat = eligible_wide.select(tickers_all).to_numpy()
adtv_mat = adtv_wide.select(tickers_all).to_numpy()

W = RISK_CONFIG["lookback_window"]
rebal_step = RISK_CONFIG["rebalance_freq_days"]
min_assets = RISK_CONFIG["min_assets_required"]
max_w = RISK_CONFIG["max_single_weight"]
n_clust = RISK_CONFIG["n_clusters"]

rec_erc, rec_ivol, rec_eq = [], [], []
curr_erc = np.zeros(len(tickers_all))
curr_ivol = np.zeros(len(tickers_all))
curr_eq = np.zeros(len(tickers_all))
prev_selected_global = set()

for t in range(W, len(dates_all)):
    d = dates_all[t]
    is_rebal = ((t - W) % rebal_step == 0)

    if is_rebal:
        # Dùng dữ liệu đến hết phiên t-1 để loại bỏ hoàn toàn look-ahead bias trong ngày t
        valid_idx = np.where(elig_mat[t - 1])[0]
        if len(valid_idx) >= min_assets:
            win_rets = np.nan_to_num(ret_mat[t - W : t, :][:, valid_idx], nan=0.0)
            win_adtv = adtv_mat[t - 1, valid_idx]

            # Bước 1: Khử nhiễu ma trận tương quan toàn rổ đủ chuẩn
            corr_full, stds_full = denoise_correlation_rmt(win_rets)

            # Bước 2: Phân cụm & Chọn mã đại diện có ưu tiên giữ danh mục cũ
            rep_sub_idx = select_cluster_representatives(
                corr_full, stds_full, win_adtv, n_clust,
                valid_global_idx=valid_idx,
                prev_selected_global=prev_selected_global,
                hysteresis_bonus=1.25
            )
            chosen_global_idx = valid_idx[rep_sub_idx]
            prev_selected_global = set(chosen_global_idx.tolist())

            # Trích xuất ma trận hiệp phương sai sạch cho riêng nhóm mã đại diện
            corr_sub = corr_full[np.ix_(rep_sub_idx, rep_sub_idx)]
            stds_sub = stds_full[rep_sub_idx]
            cov_sub = np.outer(stds_sub, stds_sub) * corr_sub

            # Bước 3: Tính tỷ trọng cho RMT-ERC và 2 đối thủ cạnh tranh
            w_erc_sub = optimize_erc_weights(cov_sub, max_weight=max_w)
            w_iv_sub, w_eq_sub = compute_benchmark_weights(stds_sub, max_weight=max_w)

            curr_erc = np.zeros(len(tickers_all)); curr_erc[chosen_global_idx] = w_erc_sub
            curr_ivol = np.zeros(len(tickers_all)); curr_ivol[chosen_global_idx] = w_iv_sub
            curr_eq = np.zeros(len(tickers_all)); curr_eq[chosen_global_idx] = w_eq_sub
        else:
            curr_erc = np.zeros(len(tickers_all))
            curr_ivol = np.zeros(len(tickers_all))
            curr_eq = np.zeros(len(tickers_all))
            prev_selected_global = set()

    for rec_list, w_vec in [(rec_erc, curr_erc), (rec_ivol, curr_ivol), (rec_eq, curr_eq)]:
        row = {"trade_date": d, "is_rebalance_day": is_rebal}
        for idx, tk in enumerate(tickers_all):
            row[tk] = w_vec[idx]
        row["CASH"] = max(0.0, 1.0 - np.sum(w_vec))
        rec_list.append(row)

df_erc = pl.DataFrame(rec_erc)
df_ivol = pl.DataFrame(rec_ivol)
df_eq = pl.DataFrame(rec_eq)

df_erc.write_parquet(OUT_ERC_PATH, compression="zstd")
df_ivol.write_parquet(OUT_IVOL_PATH, compression="zstd")
